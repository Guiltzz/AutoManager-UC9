    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String descricao = txtDescricao.getText().trim();
        String categoria = txtCategoria.getText().trim();
        String tempo = txtTempo.getText().trim();
        String valor = txtValor.getText().trim();
        String observacao = txtObservacao.getText().trim();
        Boolean ativo = cbAtivo.isSelected();
        
        BigDecimal tempoDecimal = new BigDecimal(tempo);
        BigDecimal valorDecimal = new BigDecimal(valor);
        
        String sqlInsert = """
                           INSERT INTO servico
                           (descricao,categoria,valor_base,tempo_estimado_horas,observacao,ativo)
                           VALUES (?,?,?,?,?,?)""";
        
        try(Connection conex = Conexao.conectar();
        PreparedStatement stmt = conex.prepareStatement(sqlInsert)){
            
            stmt.setString(1, descricao);
            stmt.setString(2, categoria);
            stmt.setBigDecimal(3, valorDecimal);
            stmt.setBigDecimal(4, tempoDecimal);
            stmt.setString(5, observacao);
            stmt.setBoolean(6,ativo);
            
            int linhas = stmt.executeUpdate();
            
            if (linhas > 0 ){
                txtDescricao.setText("");
                txtCategoria.setText("");
                txtValor.setText("");
                txtTempo.setText("");
                txtObservacao.setText("");
                cbAtivo.setSelected(false);
            }
                    
       }catch (SQLException erro){
           JOptionPane.showMessageDialog(this,"ERRO AO CADASTRAS :\n "+erro.getMessage(),"Erro no banco de dados",JOptionPane.ERROR_MESSAGE);
                return;
       }
    }//GEN-LAST:event_jButton1ActionPerformed

