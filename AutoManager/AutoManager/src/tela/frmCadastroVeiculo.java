    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        
        
            int cliente_id = 0;

            
            String placa = txtPlaca.getText().trim();
            String marca = txtMarca.getText().trim();
            String modelo = txtModelo.getText().trim();
            int ano = Integer.parseInt(txtAno.getText().trim());
            String cor = txtCor.getText().trim();
            String observacao = txtObservacao.getText().trim();
            Boolean ativo = cbAtivo.isSelected();
            
            if(ano > 2100 || ano <1900){
                JOptionPane.showMessageDialog(this,"Ano invalido","Digite um ano que seja entre 1900 e 2100",JOptionPane.WARNING_MESSAGE);
                return;
            }
            
            String sql = "SELECT id FROM cliente WHERE cpf = ?";
            
            try (Connection conex = Conexao.conectar();
                    
         PreparedStatement stmt = conex.prepareStatement(sql)) {
                
                stmt.setString(1, txtCpf.getText().trim());
                ResultSet rs = stmt.executeQuery();
                
                if (rs.next()) {
                    
                cliente_id = rs.getInt("id");
                
              } else {
                JOptionPane.showMessageDialog(this, "Cliente não encontrado!");
                
                return;
                
            }
            }catch (SQLException erro) {
            JOptionPane.showMessageDialog(this,
            "Erro ao buscar animal: " + erro.getMessage());
            return;
    }
            
           
            
            
            
        String sqlInsert = """
                           INSERT INTO veiculo
                           (cliente_id,placa,marca,modelo,ano,cor,observacao,ativo)
                           VALUES (?,?,?,?,?,?,?,?)
                           """;
        
        try{
            Connection conex = Conexao.conectar();
            PreparedStatement stmt = conex.prepareStatement(sqlInsert);
            
            stmt.setInt(1,cliente_id);
            stmt.setString(2,placa);
            stmt.setString(3, marca);
            stmt.setString(4,modelo);
            stmt.setInt(5,ano);
            stmt.setString(6,cor);
            stmt.setString(7, observacao);
            stmt.setBoolean(8,ativo);
            
            int linhas = stmt.executeUpdate();
            
            if (linhas > 0){
                JOptionPane.showMessageDialog(this, "Cadastro realizado com sucesso!");
                txtCpf.setText("");
                txtPlaca.setText("");
                txtMarca.setText("");
                txtModelo.setText("");
                txtAno.setText("");
                txtCor.setText("");
                txtObservacao.setText("");
                cbAtivo.setSelected(false);
                txtCpf.requestFocus();
             }
            
            
            
        }catch (SQLException erro){
            JOptionPane.showMessageDialog(this,
                    "Erro ao cadastrar  :\n" + erro.getMessage(),
                    "Erro no banco de dados",
                     JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

