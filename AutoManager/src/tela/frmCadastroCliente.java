    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
            String sqlInsert = """
                           INSERT INTO cliente 
                           (nome,cpf,telefone,email,endereco,ativo)
                           VALUES (?,?,?,?,?,?)
                           """;
            
            String nome = txtNome.getText().trim();
            String cpf = txtCpf.getText().trim();
            String telefone = txtTelefone.getText().trim();
            String email = txtEmail.getText().trim();
            String endereco = txtEndereco.getText().trim();
            Boolean ativo = cbAtivo.isSelected();
            
            if ( nome.isEmpty() || cpf.isEmpty() || telefone.isEmpty() || email.isEmpty() || endereco.isEmpty() ){
                
                JOptionPane.showMessageDialog(this,"Preencha todos os campos!");
                
                return;
            }
        
        
        try{
            Connection conex = Conexao.conectar();
            PreparedStatement stmt = conex.prepareStatement(sqlInsert);
            
            
            
            
            
            
            stmt.setString(1,nome);
            stmt.setString(2, cpf);
            stmt.setString(3, telefone);
            stmt.setString(4, email);
            stmt.setString(5, endereco);
            stmt.setBoolean(6,ativo);
            
             int linhas = stmt.executeUpdate();
             
             if (linhas > 0){
                JOptionPane.showMessageDialog(this, "Cadastro realizado com sucesso!");
                txtNome.setText("");
                txtCpf.setText("");
                txtEndereco.setText("");
                txtTelefone.setText("");
                txtEmail.setText("");
                cbAtivo.setSelected(false);
                txtNome.requestFocus();
             }
             
        }catch (SQLException erro){
            JOptionPane.showMessageDialog(this,"Não foi possível Cadastrar! - Erro: "+ erro);
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

