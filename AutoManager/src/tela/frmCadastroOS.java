    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        String sqlInsert = """
                           INSERT INTO ordem_servico 
                           (veiculo_id,mecanico_id,servico_id,data_conclusao,descricao_problema,diagnostico,status,valor_cobrado,observacao)
                           VALUES (?,?,?,?,?,?,?,?,?)""";
        
        int veiculo_id ;
        int mecanico_id ;
        int servico_id ;
        
        String dataAbert = txtDataAbert.getText().trim();
        String dataConc = txtDataConc.getText().trim();
        String problema = txtProblema.getText().trim();
        String diagnostico = txtDiagnostico.getText().trim();
        String valor = txtValor.getText().trim();
        String observacao = txtObservacao.getText().trim();
        String status = cbEstado.getSelectedItem().toString();
        
        BigDecimal valorDecimal =  new BigDecimal(valor);
        
        String status_banco ="";
        
        
        
        String sqlVeiculo = "SELECT id FROM veiculo WHERE id = ?";
        String sqlMecanico = "SELECT id FROM mecanico WHERE id = ?";
        String sqlServico = "SELECT id FROM servico WHERE id = ?";
        
        
        
        
        
        
        if (problema.isEmpty()  || valor.isEmpty() || dataAbert.isEmpty() || dataConc.isEmpty()){
            JOptionPane.showMessageDialog(this, "Preencha todos os campos obrigatórios");
        }
        
        
            
            
        if (status.equals("Aberto")){
            status_banco = "ABERTA";
            
        }else if (status.equals("Em andamento")){
            status_banco = "EM_ANDAMENTO";
        
        }else if (status.equals("Concluido")){
            status_banco = "CONCLUIDO";
            
        }else if (status.equals("Cancelado")){
            status_banco = "CANCELADO";
        }
        
        
        
        
        ///////////////////////////////////////////////////TRY VEICULO/////////////////////////////////////////////////////////////////
        
        
        try (Connection conex = Conexao.conectar();
                    
         PreparedStatement stmt = conex.prepareStatement(sqlVeiculo)) {
            
            stmt.setInt(1, Integer.parseInt(txtIdVeiculo.getText().trim()));
                ResultSet rs = stmt.executeQuery();
                
                if (rs.next()) {
                    
                veiculo_id = rs.getInt("id");
                
              } else {
                JOptionPane.showMessageDialog(this, "Veiculo não encontrado!\n Verifique o id");
                
                return;
                
            }
            
        }catch (SQLException erro){
             JOptionPane.showMessageDialog(this,
                    "Erro ao cadastrar  :\n" + erro.getMessage(),
                    "Erro no banco de dados",
                     JOptionPane.ERROR_MESSAGE);
             return;
        }
        
        
        
        
        
        ///////////////////////////////////////////////////TRY MECANICO/////////////////////////////////////////////////////////////////
        
        try (Connection conex = Conexao.conectar();
                    
         PreparedStatement stmt = conex.prepareStatement(sqlMecanico)) {
            stmt.setInt(1, Integer.parseInt(txtIdMecanico.getText().trim()));
                ResultSet rs = stmt.executeQuery();
                
                if (rs.next()) {
                    
                mecanico_id = rs.getInt("id");
                
              } else {
                JOptionPane.showMessageDialog(this, "Mecanico não encontrado!\n Verifique o id");
                
                return;
                
            }
            
        }catch (SQLException erro){
             JOptionPane.showMessageDialog(this,
                    "Erro ao cadastrar  :\n" + erro.getMessage(),
                    "Erro no banco de dados",
                     JOptionPane.ERROR_MESSAGE);
             return;
        }
        
        
        
        
        
        
        ///////////////////////////////////////////////////TRY SERVICO/////////////////////////////////////////////////////////////////
        
        try (Connection conex = Conexao.conectar();
                    
         PreparedStatement stmt = conex.prepareStatement(sqlServico)) {
         stmt.setInt(1, Integer.parseInt(txtIdServico.getText().trim())); 
                ResultSet rs = stmt.executeQuery();
                
                if (rs.next()) {
                    
                servico_id = rs.getInt("id");
                
              } else {
                JOptionPane.showMessageDialog(this, "Serviço não encontrado!\n Verifique o id");
                
                return;
                
            }
            
        }catch (SQLException erro){
             JOptionPane.showMessageDialog(this,
                    "Erro ao cadastrar  :\n" + erro.getMessage(),
                    "Erro no banco de dados",
                     JOptionPane.ERROR_MESSAGE);
             return;
        }
        
        
        
        
        ///////////////////////////////////////////////////TRY INSERT/////////////////////////////////////////////////////////////////
        
        try(Connection conex = Conexao.conectar();
        PreparedStatement stmt = conex.prepareStatement(sqlInsert)){
            
            stmt.setInt(1,veiculo_id);
            stmt.setInt(2, mecanico_id);
            stmt.setInt(3,servico_id);
            
            ///////////////////////////////////////////////////////////////////////
            DateTimeFormatter fmt = DateTimeFormatter.ofPattern("dd/MM/yyyy");

            // if (dataConc.replaceAll("[^0-9]", "").isEmpty()) {
            //stmt.setNull(4, java.sql.Types.DATE);
            //} else {
            //stmt.setDate(4, java.sql.Date.valueOf(LocalDate.parse(dataConc, fmt)));
            //}
            /////////////////////////////////////////////////////////////////////////
            
            stmt.setString(5, problema);
            stmt.setString(6, diagnostico);
            stmt.setString(7, status_banco);
            stmt.setBigDecimal(8, valorDecimal);
            stmt.setString(9, observacao);
            
            int linhas = stmt.executeUpdate();
            
            if (linhas > 0){
                JOptionPane.showMessageDialog(this, "Cadastro realizado com sucesso!");
                txtIdVeiculo.setText("");
                txtIdMecanico.setText("");
                txtIdServico.setText("");
                txtDataAbert.setText("");
                txtDataConc.setText("");
                txtProblema.setText("");
                txtDiagnostico.setText("");
                txtValor.setText("");
                txtObservacao.setText("");
                cbEstado.setSelectedItem("Aberto");
                txtIdVeiculo.requestFocus();
             }
            
        }catch (SQLException erro){
                JOptionPane.showMessageDialog(this,"ERRO AO CADASTRAS :\n "+erro.getMessage(),"Erro no banco de dados",JOptionPane.ERROR_MESSAGE);
                return;
                }
        
        
    }//GEN-LAST:event_btnSalvarActionPerformed

