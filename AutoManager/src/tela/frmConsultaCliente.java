    private void btnPesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPesquisarActionPerformed
        String pesquisa = txtPesquisar.getText().trim();
        String tipo_pesquisa = cbPesquisar.getSelectedItem().toString();
        
         if (pesquisa.isEmpty()){
            JOptionPane.showMessageDialog(
                        this,
                        "Digite o id, nome, cpf ou telefone.",
                        "Pesquisa Vazia",
                        JOptionPane.WARNING_MESSAGE);
            return;
        }
         
         DefaultTableModel modelo = (DefaultTableModel) tabCliente.getModel();
        
        modelo.setRowCount(0);
        
        
        
        String sql ="";
        
        Integer id = null;
        
        if (tipo_pesquisa.equals("Id")) {
        try {
            id = Integer.parseInt(pesquisa);
            
            sql = "SELECT * FROM cliente WHERE id = ? ORDER BY id";
            
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "ID deve ser numérico.");
            return;
        }
        
        if (tipo_pesquisa == "Nome") {
        
             sql = "SELECT * FROM cliente "
                   + "WHERE nome ILIKE ? "
                   + "ORDER BY nome";
                }
        
        else if (tipo_pesquisa == "CPF"){
        
             sql = "SELECT * FROM cliente "
                   + "WHERE cpf  ? ";
        }
        else if (tipo_pesquisa == "Telefone"){
                sql = "SELECT * FROM cliente"
                        + "WHERE telefone ?";
                }
        
        try (Connection conex = Conexao.conectar();
                
              PreparedStatement stmt = conex.prepareStatement(sql)){
            stmt.setString(1,"%" + pesquisa + "%");
            
            try (ResultSet resultado = stmt.executeQuery()){
                while (resultado.next()){
                    modelo.addRow(new Object [] {
                        resultado.getInt("id"),
                        resultado.getString("nome"),
                        resultado.getString("cpf"),
                        resultado.getString("telefone") });
                }
            }
            if (modelo.getRowCount() == 0){
             JOptionPane.showMessageDialog(this,
                           "Nenhum Cliente encontrado para: " + pesquisa,
                           "Resultado da Pesquisa",
                           JOptionPane.INFORMATION_MESSAGE);
              }
        } catch (SQLException erro){
            JOptionPane.showMessageDialog(this,
                    "Erro ao localizar  :\n" + erro.getMessage(),
                    "Erro no banco de dados",
                     JOptionPane.ERROR_MESSAGE);
        }
        } 
    }//GEN-LAST:event_btnPesquisarActionPerformed

